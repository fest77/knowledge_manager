# -*- coding: utf-8 -*-
"""停用词表（模块 00 公共基础，模块 08 的问法归一化使用）。

## 唯一的硬约束：**宁可少合并，不可错合并**

归一化把不同问法合并成同一条缺口，靠的是"去掉不携带知识内容的词"。
去错一个词的代价是**语义反转**：把「年假**能**折现吗」与「年假**不能**折现吗」
合并成一条 —— 那就不是"少一条缺口"，而是"缺口清单在说反话"。

所以本表按三条规矩维护：

| 类别 | 处理 | 例 |
|---|---|---|
| 疑问虚词、助词结构词、英文冠词/be | **去** | 吗 / 呢 / 请问 / 的 / 了 / the / is |
| **否定词** | **绝对不去** | 不 / 没 / 无 / 未 / 非 / 别 / 莫 |
| **程度与数量词** | **不去** | 最 / 多少 / 几 / 上限 / 阈值 |

第三条容易被"顺手"加进去（"『上限是多少』与『上限』不是一回事吗？"）——
不是：「报销上限是多少」问的是**数值**，「报销上限」可能是在问**规定本身**。
留着它只是少合并几条，去掉它却可能把两个不同问题算成一件事。

> 也不做同义词替换、不做词干化、不做拼音归一 —— 同义换词的合并在 08 里
> **规则覆盖不了**（「差旅」vs「出差」），那是 07 的向量聚类职责（AD-06）。
"""
from __future__ import annotations

from functools import lru_cache

# 中文按**字**过滤（中文问句里这些字几乎只作虚词）
CN_STOP: frozenset[str] = frozenset(
    # 疑问虚词（按字与按词两种粒度都覆盖）
    "吗呢吧啊呀么嘛"
    # 助词与结构词
    "的了着过地得"
    "是"
    # 常见提问客套（单字层面能覆盖的）
    "请教"
)

# 多字疑问短语：在归一化时按**整体**删除（按字删会把"请问"拆成"请""问"，
# 而"问"在一些问句里是有意义的动词）
CN_STOP_PHRASES: tuple[str, ...] = (
    "请问", "请教一下", "请问一下", "我想问", "想问一下", "帮我看看",
    "一下", "的话", "是不是", "有没有",
)

# 英文按**词**过滤
EN_STOP: frozenset[str] = frozenset({
    "the", "a", "an", "is", "are", "was", "were", "be", "been", "being",
    "of", "to", "for", "and", "or", "in", "on", "at", "it", "this", "that",
    "please", "how", "what", "which", "can", "could", "do", "does", "did",
})


@lru_cache(maxsize=1)
def load_stopwords() -> tuple[frozenset[str], frozenset[str]]:
    """返回 `(中文字停用集, 英文词停用集)`。

    `lru_cache` 不是为了性能（表只有几十项），而是为了**保证每次拿到同一份**：
    归一化是唯一索引键的输入，任何"这次多去了一个词、下次没去"的差异
    都会让同一句话在两个时刻产生两个 `normalized_key`。
    """
    return CN_STOP, EN_STOP


__all__ = ["CN_STOP", "CN_STOP_PHRASES", "EN_STOP", "load_stopwords"]
